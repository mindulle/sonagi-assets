#!/usr/bin/env python3
"""브랜드 시각 언어 → 디자인 토큰(primitives/semantic/CSS/Figma JSON) 생성.

SSOT는 `mindulle-visual-style` 스킬의 두 팔레트다.
- Editorial(뉴스프린트): 종이 배경 + 잉크 + 단일 골드 악센트
- Architecture(다크): 60-30-10, 레인 블루 + 앰버

지원 색상 램프(상태·호버용)는 Radix Colors(MIT)에서 가져와 primitives로 둔다.
브랜드 코어 값은 semantic에서 고정한다.

사용::

    python3 build_design_tokens.py \
        --radix node_modules/@radix-ui/colors \
        --out tokens
"""

import argparse
import json
import re
from pathlib import Path

LIGHT_SCALES = ["sand", "amber", "blue", "cyan", "red", "green"]
DARK_SCALES = [f"{s}-dark" for s in ("sand", "amber", "blue", "cyan", "red", "green")]

SPACE = {"1": "4px", "2": "8px", "3": "12px", "4": "16px", "5": "24px", "6": "32px", "7": "48px", "8": "64px"}
RADIUS = {"1": "4px", "2": "6px", "3": "8px"}

TYPE = {
    "h1": {"size": "64px", "leading": "1.1", "tracking": "-0.02em", "weight": "700", "font": "display"},
    "h2": {"size": "36px", "leading": "1.2", "tracking": "-0.01em", "weight": "700", "font": "sans"},
    "h3": {"size": "24px", "leading": "1.3", "tracking": "0", "weight": "600", "font": "sans"},
    "body": {"size": "16px", "leading": "1.6", "tracking": "0", "weight": "400", "font": "sans"},
    "caption": {"size": "12px", "leading": "1.4", "tracking": "0.05em", "weight": "500", "font": "mono"},
    "micro": {"size": "10px", "leading": "1.2", "tracking": "0.22em", "weight": "600", "font": "mono"},
}

FONTS = {
    "display": "'Cormorant Garamond', Georgia, serif",
    "sans": "Pretendard, Inter, system-ui, sans-serif",
    "mono": "'JetBrains Mono', ui-monospace, monospace",
}


def read_scale(path):
    text = path.read_text(errors="ignore")
    block = text.split("}", 1)[0]
    out = {}
    for step, value in re.findall(r"--[\w-]+-(\d+):\s*(#[0-9a-fA-F]{6})", block):
        out[step] = value.lower()
    return out


def dump_json(path, obj):
    """biome(prettier) 규칙에 맞춰 4-space + 개행으로 쓴다."""
    path.write_text(json.dumps(obj, indent=4, ensure_ascii=False) + "\n")


def build_primitives(radix_dir):
    primitives = {}
    for name in LIGHT_SCALES + DARK_SCALES:
        path = Path(radix_dir) / f"{name}.css"
        if path.is_file():
            scale = read_scale(path)
            if scale:
                primitives[name] = scale
    return primitives


def build_semantic():
    editorial = {
        "background": "#fbf9f5",
        "surface": "#ffffff",
        "surface-sunken": "#f4f1ea",
        "ink": "#161616",
        "text": "#161616",
        "text-secondary": "#3a3a36",
        "text-muted": "#63635e",
        "text-faint": "#8d8d86",
        "accent": "#d97706",
        "accent-strong": "#f59e0b",
        "accent-ink": "#161616",
        "border": "#dcd7cc",
        "border-strong": "#161616",
        "success": "#2f7a4f",
        "warning": "#b45309",
        "danger": "#b42318",
        "info": "#1d4ed8",
    }
    architecture = {
        "background": "#060911",
        "surface": "#090d16",
        "surface-sunken": "#04060c",
        "ink": "#ffffff",
        "text": "#ffffff",
        "text-secondary": "#c9d1d9",
        "text-muted": "#9aa4b2",
        "text-faint": "#6b7280",
        "accent": "#4a90e2",
        "accent-strong": "#ffd166",
        "accent-ink": "#060911",
        "border": "#30363d",
        "border-strong": "#4a5260",
        "success": "#3fb950",
        "warning": "#ffd166",
        "danger": "#f85149",
        "info": "#4a90e2",
        "terminal": "#00ffcc",
    }
    return {"editorial": editorial, "architecture": architecture}


def css_block(theme, sem):
    lines = [f'[data-theme="{theme}"], .theme-{theme} {{']
    for key, value in sem.items():
        lines.append(f"  --mds-color-{key}: {value};")
    lines.append("}")
    return "\n".join(lines)


def write_css(path, primitives, semantic):
    out = ["/* generated by scripts/build_design_tokens.py — 직접 수정 금지 */", ":root {"]
    for scale, steps in primitives.items():
        for step, value in sorted(steps.items(), key=lambda kv: int(kv[0])):
            out.append(f"  --mds-{scale}-{step}: {value};")
    for name, value in SPACE.items():
        out.append(f"  --mds-space-{name}: {value};")
    for name, value in RADIUS.items():
        out.append(f"  --mds-radius-{name}: {value};")
    for name, value in FONTS.items():
        out.append(f"  --mds-font-{name}: {value};")
    out.append("  --mds-border-width: 2px;")
    out.append("  --mds-border-hairline: 1px;")
    out.append("  --mds-shadow-crisp: 2px 2px 0 var(--mds-color-border-strong);")
    for step, spec in TYPE.items():
        out.append(f"  --mds-text-{step}-size: {spec['size']};")
        out.append(f"  --mds-text-{step}-leading: {spec['leading']};")
        out.append(f"  --mds-text-{step}-tracking: {spec['tracking']};")
        out.append(f"  --mds-text-{step}-weight: {spec['weight']};")
    out.append("}")
    # 기본 테마 = editorial
    default = semantic["editorial"]
    out.append(':root, [data-theme="editorial"], .theme-editorial {')
    for key, value in default.items():
        out.append(f"  --mds-color-{key}: {value};")
    out.append("}")
    out.append(css_block("architecture", semantic["architecture"]))
    path.write_text("\n".join(out) + "\n")


def figma_json(semantic):
    return {
        "global": {
            "color": {k: {"value": v, "type": "color"} for k, v in semantic["editorial"].items()},
            "space": {k: {"value": v, "type": "spacing"} for k, v in SPACE.items()},
            "radius": {k: {"value": v, "type": "borderRadius"} for k, v in RADIUS.items()},
            "font": {k: {"value": v, "type": "fontFamilies"} for k, v in FONTS.items()},
            "text": {f"{k}-size": {"value": v["size"], "type": "fontSizes"} for k, v in TYPE.items()},
        },
        "editorial": {
            "color": {k: {"value": v, "type": "color"} for k, v in semantic["editorial"].items()},
        },
        "architecture": {
            "color": {k: {"value": v, "type": "color"} for k, v in semantic["architecture"].items()},
        },
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--radix", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    primitives = build_primitives(args.radix)
    semantic = build_semantic()

    dump_json(out / "primitives.json", primitives)
    dump_json(out / "semantic.json", semantic)
    dump_json(out / "tokens.figma.json", figma_json(semantic))
    write_css(out / "tokens.css", primitives, semantic)

    print(
        json.dumps(
            {
                "scales": sorted(primitives),
                "colors": len(semantic["editorial"]),
                "type_steps": len(TYPE),
                "out": str(out),
            },
            ensure_ascii=False,
        )
    )


if __name__ == "__main__":
    main()
